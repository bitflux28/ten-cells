# Builds Ten Cells native: python3 build.py [linux|windows] -> build/<target>/
# raylib 5.5 (window, drawing, audio) + quickjs-ng (runs the web game's rules unchanged) + our C++.
import os, subprocess, sys, pathlib, hashlib, shutil
R = pathlib.Path(__file__).resolve().parent
T = sys.argv[1] if len(sys.argv) > 1 else 'linux'
OUT = R / 'build' / T; OBJ = OUT / 'obj'; OBJ.mkdir(parents=True, exist_ok=True)
RL, QJ = R / 'ext/raylib/src', R / 'ext/quickjs'
ZIG = [sys.executable, '-m', 'ziglang']
if T == 'windows':
    CC, CXX = ZIG + ['cc', '-target', 'x86_64-windows-gnu'], ZIG + ['c++', '-target', 'x86_64-windows-gnu']
    PLAT = ['-D_GLFW_WIN32']; LIBS = ['-lopengl32', '-lgdi32', '-lwinmm', '-lshell32', '-lole32', '-luuid', '-lws2_32', '-ladvapi32', '-Wl,--subsystem,windows', '-static']
    EXE = OUT / 'Ten Cells.exe'
else:
    CC, CXX = ['gcc'], ['g++']
    PLAT = ['-D_GLFW_X11', f'-I{R}/ext/xhdr']; LIBS = ['-lm', '-ldl', '-lpthread', '-lX11']
    EXE = OUT / 'tencells'
OPT = ['-O2', '-g0']
RL_SRC = ['rcore.c', 'rshapes.c', 'rtextures.c', 'rtext.c', 'rmodels.c', 'raudio.c', 'utils.c', 'rglfw.c']
QJ_SRC = ['dtoa.c', 'libregexp.c', 'libunicode.c', 'quickjs.c']

# ---- embed the rules scripts, fonts, sprite sheet and icon into the program (src/embed.cpp, regenerated when they change) ----
import json as _json
from fontTools.ttLib import TTFont
EMB = [('shim_js', R/'js/shim.js'), ('decimal_js', R/'js/decimal.js'), ('data_js', R/'js/data.js'), ('logic_js', R/'js/logic.js'), ('api_js', R/'js/api.js'),
       ('font_px', R/'assets/PXNumbers400.ttf'), ('font_bold', R/'assets/PixelifySans700.ttf'), ('sprites_png', R/'assets/sprites.png'), ('icon_png', R/'assets/icon.png')]
def _arr(name, data): return f'const unsigned char EMB_{name}[] = {{' + ','.join(map(str, data)) + f'}};\nconst size_t EMB_{name}_len = {len(data)};\n'
sig = hashlib.md5(b''.join(p.read_bytes() for _, p in EMB)).hexdigest()
ec, eh = R/'src/embed.cpp', R/'src/embed.h'
if not ec.exists() or sig not in ec.read_text()[:200]:
    spr = _json.loads((R/'assets/sprites.json').read_text())
    cps = sorted(set(TTFont(str(R/'assets/PXNumbers400.ttf')).getBestCmap()) | set(TTFont(str(R/'assets/PixelifySans700.ttf')).getBestCmap()))
    body = f'// generated by build.py from js/ and assets/, sig {sig}\n#include "embed.h"\n' + ''.join(_arr(n, p.read_bytes()) for n, p in EMB)
    body += 'const char *EMB_sprite_names[] = {' + ','.join(_json.dumps(x) for x in spr['names']) + f'}};\nconst int EMB_sprite_count = {len(spr["names"])}, EMB_sprite_w = {spr["W"]}, EMB_sprite_h = {spr["H"]}, EMB_sprite_cols = {spr["cols"]};\n'
    body += 'int EMB_codepoints[] = {' + ','.join(map(str, cps)) + f'}};\nconst int EMB_codepoint_count = {len(cps)};\n'
    ec.write_text(body)
    eh.write_text('#pragma once\n#include <cstddef>\n' + ''.join(f'extern const unsigned char EMB_{n}[]; extern const size_t EMB_{n}_len;\n' for n, _ in EMB) +
                  'extern const char *EMB_sprite_names[]; extern const int EMB_sprite_count, EMB_sprite_w, EMB_sprite_h, EMB_sprite_cols;\nextern int EMB_codepoints[]; extern const int EMB_codepoint_count;\n')
    print('embedded', len(EMB), 'files,', len(cps), 'glyphs')
APP_SRC = sorted(p.name for p in (R / 'src').glob('*.cpp'))

def compile_(cc, src, flags):
    o = OBJ / (src.stem + '.o')
    key = hashlib.md5((str(src.stat().st_mtime) + ' '.join(flags)).encode()).hexdigest()
    stamp = o.with_suffix('.k')
    deps_new = any(h.stat().st_mtime > o.stat().st_mtime for h in (R / 'src').glob('*.h')) if o.exists() and src.parent == R / 'src' else False
    if o.exists() and stamp.exists() and stamp.read_text() == key and not deps_new: return o
    r = subprocess.run(cc + ['-c', str(src), '-o', str(o)] + flags, capture_output=True, text=True)
    if r.returncode: print(r.stderr[-4000:]); sys.exit(f'compile failed: {src.name}')
    stamp.write_text(key); return o

objs = []
for f in RL_SRC: objs.append(compile_(CC, RL / f, OPT + ['-DPLATFORM_DESKTOP', '-DGRAPHICS_API_OPENGL_33', f'-I{RL}', f'-I{RL}/external/glfw/include', '-w'] + PLAT))
for f in QJ_SRC: objs.append(compile_(CC, QJ / f, OPT + ['-D_GNU_SOURCE', f'-I{QJ}', '-w']))
for f in APP_SRC: objs.append(compile_(CXX, R / 'src' / f, OPT + ['-std=c++17', f'-I{RL}', f'-I{QJ}', f'-I{R}/src', '-Wall', '-Wno-unused-function'] + (['-DTC_WINDOWS'] if T == 'windows' else [])))
if T == 'windows':
    rc = OBJ / 'app.rc'; rc.write_text(f'1 ICON "{(R / "assets/icon.ico").as_posix()}"\n')
    res = OBJ / 'app.res'
    r = subprocess.run(ZIG + ['rc', '--', str(rc), str(res)], capture_output=True, text=True)
    if r.returncode: print(r.stderr[-2000:]); sys.exit('icon resource failed')
    objs.append(res)
r = subprocess.run(CXX + [str(o) for o in objs] + ['-o', str(EXE)] + LIBS, capture_output=True, text=True)
if r.returncode: print(r.stderr[-4000:]); sys.exit('link failed')
print('built', EXE, round(EXE.stat().st_size / 1e6, 2), 'MB')
